#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." >/dev/null 2>&1 && pwd)"

# Find gpasm
if command -v gpasm >/dev/null 2>&1; then
    GPASM="gpasm"
    INC_DIR=""
elif [ -x "${REPO_ROOT}/tools/gputils/usr/bin/gpasm" ]; then
    GPASM="${REPO_ROOT}/tools/gputils/usr/bin/gpasm"
    INC_DIR="-I ${REPO_ROOT}/tools/gputils/usr/share/gputils/header"
else
    echo "Error: gpasm not found in PATH or tools/gputils." >&2
    exit 1
fi

BUILD_DIR="${1:-${REPO_ROOT}/build/pic}"
mkdir -p "${BUILD_DIR}"

SRC="${REPO_ROOT}/src/pic/sensor.asm"
HEX_OUT="${BUILD_DIR}/sensor.hex"
COD_OUT="${BUILD_DIR}/sensor.cod"
LST_OUT="${BUILD_DIR}/sensor.lst"

# Derive version from Sesame app version & git commit count
VER_FILE="${REPO_ROOT}/VERSION"
APP_MAJOR=$(grep -E '^\s*VERSION_MAJOR\s*=' "${VER_FILE}" | awk -F'=' '{print $2}' | tr -d ' ')
APP_MINOR=$(grep -E '^\s*VERSION_MINOR\s*=' "${VER_FILE}" | awk -F'=' '{print $2}' | tr -d ' ')
APP_PATCH=$(grep -E '^\s*PATCHLEVEL\s*=' "${VER_FILE}" | awk -F'=' '{print $2}' | tr -d ' ')
APP_TAG="v${APP_MAJOR}.${APP_MINOR}.${APP_PATCH}"
COMMIT_COUNT=$(git -C "${REPO_ROOT}" rev-list --count "${APP_TAG}..HEAD" 2>/dev/null || echo 0)

APP_MAJOR=${APP_MAJOR:-0}
APP_MINOR=${APP_MINOR:-2}
APP_PATCH=${APP_PATCH:-9}
COMMIT_COUNT=${COMMIT_COUNT:-0}

# Generate pic_version.inc
PIC_INC="${BUILD_DIR}/pic_version.inc"
cat <<EOF > "${PIC_INC}"
; Auto-generated by Sesame build system. Do not edit.
#define PIC_VER_MAJOR ${APP_MAJOR}
#define PIC_VER_MINOR ${APP_MINOR}
#define PIC_VER_PATCH ${APP_PATCH}
#define PIC_VER_COMMIT ${COMMIT_COUNT}
EOF

echo "Assembling ${SRC} for PIC16LF15355 (v${APP_MAJOR}.${APP_MINOR}.${APP_PATCH}+${COMMIT_COUNT})..."
${GPASM} ${INC_DIR} -I "${BUILD_DIR}" -I "${REPO_ROOT}/src/pic" \
    "${SRC}" -o "${HEX_OUT}"

echo "Successfully built PIC firmware: ${HEX_OUT}"
ls -lh "${HEX_OUT}"

# Generate C source and header embedding the hex file
HEX_C="${BUILD_DIR}/pic_firmware_hex.c"
HEX_H="${BUILD_DIR}/pic_firmware_hex.h"

cat <<EOF > "${HEX_H}"
/* Auto-generated from sensor.hex by build_pic.sh. Do not edit. */
#pragma once
#include <stddef.h>
#include <stdint.h>

#define PIC_EXPECTED_VER_MAJOR ${APP_MAJOR}
#define PIC_EXPECTED_VER_MINOR ${APP_MINOR}
#define PIC_EXPECTED_VER_PATCH ${APP_PATCH}
#define PIC_EXPECTED_VER_COMMIT ${COMMIT_COUNT}

extern const uint8_t pic_firmware_hex[];
extern const size_t pic_firmware_hex_len;
EOF

python3 -c "
with open('${HEX_OUT}', 'rb') as f:
    data = f.read()
with open('${HEX_C}', 'w') as f:
    f.write('/* Auto-generated from sensor.hex by build_pic.sh. Do not edit. */\n')
    f.write('#include \"pic_firmware_hex.h\"\n\n')
    f.write(f'const uint8_t pic_firmware_hex[{len(data)}] = {{\n')
    for i in range(0, len(data), 16):
        chunk = data[i:i+16]
        f.write('    ' + ', '.join(f'0x{b:02x}' for b in chunk) + ',\n')
    f.write('};\n')
    f.write(f'const size_t pic_firmware_hex_len = {len(data)};\n')
"

echo "Generated ${HEX_C} and ${HEX_H}"
